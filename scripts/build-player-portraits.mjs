#!/usr/bin/env node
// Makes the portrait crops listed in data/player-portraits.json (assets/players/<playerId>.webp, 208px square: twice
// the largest size shown) and regenerates lib/player-portrait-images.ts. Each crop comes from the entry's `original`
// image (a Wikimedia Commons file or its Commons thumbnail) at the entry's square `crop`, in that image's pixels.
//
//   node scripts/build-player-portraits.mjs [--from <dir>]
//
// --from: a folder of already downloaded copies named <playerId>.<ext> (originals or Commons thumbnails) (the cloud environment can't reach
// Wikimedia; a GitHub runner can, and then needs no --from). Only checked entries are listed in the data file; this
// script never looks for or adds a photo.
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const SIZE = 208;
const from = process.argv.includes("--from") ? process.argv[process.argv.indexOf("--from") + 1] : undefined;
const { portraits } = JSON.parse(readFileSync("data/player-portraits.json", "utf8"));
mkdirSync("assets/players", { recursive: true });

for (const p of portraits) {
  let input;
  const local = from && readdirSync(from).find((f) => f.startsWith(`${p.playerId}.`));
  if (local) input = readFileSync(join(from, local));
  else {
    const res = await fetch(p.original, { headers: { "User-Agent": "lol-drafting-portraits/1.0 (+https://github.com/adequate-alan/lol-drafting)" } });
    if (!res.ok) throw new Error(`${p.name}: ${p.original} answered ${res.status}`);
    input = Buffer.from(await res.arrayBuffer());
  }
  // A downloaded copy at another size (a Commons thumbnail) gets the crop scaled to it.
  const width = (await sharp(input).metadata()).width, k = width / p.originalWidth;
  const left = Math.round(p.crop.left * k), top = Math.round(p.crop.top * k), size = Math.round(p.crop.size * k);
  await sharp(input).extract({ left, top, width: size, height: size }).resize(SIZE, SIZE).webp({ quality: 80 }).toFile(p.file);
  console.log(`${p.name}: ${p.file}`);
}
// Crops no longer listed are removed with their import.
const listed = new Set(portraits.map((p) => `${p.playerId}.webp`));
for (const f of readdirSync("assets/players")) if (!listed.has(f)) unlinkSync(join("assets/players", f));

const sorted = [...portraits].sort((a, b) => a.playerId - b.playerId);
writeFileSync("lib/player-portrait-images.ts", `// Generated by scripts/build-player-portraits.mjs from data/player-portraits.json: one static import per checked portrait
// (assets/players/<playerId>.webp), so the build fingerprints them under the site's base path. Do not edit by hand.
import type { StaticImageData } from "next/image";
${sorted.map((p) => `import p${p.playerId} from "@/assets/players/${p.playerId}.webp";`).join("\n")}

export const PORTRAIT_IMAGES: Record<number, StaticImageData> = {${sorted.length ? `\n${sorted.map((p) => `  ${p.playerId}: p${p.playerId},`).join("\n")}\n` : ""}};
`);
if (!existsSync("lib/player-portrait-images.ts")) throw new Error("not written");
