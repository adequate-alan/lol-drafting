// Item changes on historical Pro Builds (alan, 2026-11-10; lib/item-history.ts, components/ItemChanges.tsx,
// scripts/item-history.ts). The item history follows Riot's stored patch notes, patches order numerically, a change counts
// only after the game's own patch (or a later-dated mid-patch update), coverage gaps are said, an item held after its
// removal is a data-quality flag, and a Common build reads each item against its own games' patches.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { buildItems, checkBuild, combined, commonMarks, itemHistoryFrom, itemVerdict, patchSpan } from "@/lib/item-history";
import { rows } from "@/lib/pro-builds-bundle";
import { Files, type ItemChange, type ItemChanges } from "@/lib/schema";

const raw = (f: string) => JSON.parse(readFileSync(join(process.cwd(), "data", f), "utf8"));
const notes = Files["patch-notes.json"].parse(raw("patch-notes.json"));
const assets = Files["build-assets.json"].parse(raw("build-assets.json")).patches;
const history = Files["item-changes.json"].parse(raw("item-changes.json"));

const change = (o: Partial<ItemChange> & Pick<ItemChange, "item" | "patch" | "type">): ItemChange => ({
  id: `${o.patch}/${o.item}`, itemId: null, basis: "riot-wording", mode: "summoners-rift", source: { url: "https://www.leagueoflegends.com/en-us/" },
  lines: [], origin: "riot-patch-notes", refreshStatus: "verified", lastChecked: "2026-11-10", ...o,
});
const hist = (changes: ItemChange[], patches: string[], external: ItemChange[] = []): Pick<ItemChanges, "archive" | "changes" | "external"> => ({
  archive: { first: patches.at(-1)!, latest: patches[0], patches: patches.map((patch) => ({ patch, url: "https://www.leagueoflegends.com/en-us/", published: null })) },
  changes, external,
});

describe("the stored history", () => {
  it("is in step with the stored patch notes (regenerated by scripts/item-history.ts)", () => {
    expect(itemHistoryFrom(notes, assets, history)).toEqual({ archive: history.archive, changes: history.changes });
  });
  it("names the newest stored patch as the live patch and every item entry of every patch", () => {
    expect(history.archive.latest).toBe([...notes.patches].map((p) => p.patch).sort((a, b) => b.localeCompare(a, undefined, { numeric: true }))[0]);
    const entries = notes.patches.flatMap((p) => p.entries.filter((e) => e.kind === "item").map((e) => `${p.patch}/${e.id}`));
    for (const e of entries) expect(history.changes.some((c) => c.id.startsWith(e))).toBe(true);
    for (const c of history.changes) expect(c.mode).toBe("summoners-rift");
  });
  it("keeps Opportunity's removal as a reported claim until the site's check reads Riot's page", () => {
    const opp = history.external.find((c) => c.item === "Opportunity")!;
    expect(opp).toMatchObject({ patch: "26.9", type: "removed", source: { url: expect.stringContaining("patch-26-9-notes") } });
    if (opp.refreshStatus !== "verified") expect(opp).toMatchObject({ origin: "externally-provided", lastChecked: null, pendingClaim: expect.anything() });
    for (const c of history.external) expect(c.source.url).not.toMatch(/utm_/);
  });
});

describe("Riot's direction for an item", () => {
  const find = (patch: string, item: string) => history.changes.find((c) => c.patch === patch && c.item === item)!;
  it("follows Riot's stated intent, and says Changed when the change goes both ways", () => {
    expect(find("26.22", "Doran's Bow").type).toBe("nerf");
    expect(find("26.21", "Dawncore").type).toBe("buff");
    expect(find("26.22", "Overlord's Bloodmail")).toMatchObject({ type: "changed", basis: "mixed" }); // "a net buff for most other users"
    expect(find("26.21", "Hubris").type).toBe("changed"); // melee up, ranged down
    expect(find("26.20", "Hextech Rocketbelt").type).toBe("changed"); // haste down, active damage up
  });
  it("reads plain stat lines only when Riot is silent and every line moves one way", () => {
    expect(find("26.17", "Stormrazor")).toMatchObject({ type: "buff", basis: "stat-lines" });
    expect(itemVerdict(undefined, [{ label: "Attack Damage", before: "40", after: "45" }, { label: "Total Cost", before: "3000g", after: "3100g" }]).type).toBe("changed");
    expect(itemVerdict(undefined, [{ label: "Total Cost", before: "1000g", after: "1100g" }]).type).toBe("nerf");
    expect(itemVerdict(undefined, [{ label: "Unique Passive", text: "Now also slows" }])).toEqual({ type: "changed", basis: "unstated" });
  });
  it("splits a heading that names two items", () => {
    expect(history.changes.filter((c) => c.patch === "26.19").map((c) => c.item)).toEqual(expect.arrayContaining(["World Atlas", "Runic Compass"]));
  });
  it("combines several changes without calling a mixed history a buff or a nerf", () => {
    const n = change({ item: "X", patch: "26.17", type: "nerf" }), b = change({ item: "X", patch: "26.16", type: "buff" });
    expect(combined([n, b])).toBe("changed");
    expect(combined([n, n])).toBe("nerf");
    expect(combined([b, change({ item: "X", patch: "26.18", type: "removed" })])).toBe("removed");
  });
});

describe("one game", () => {
  it("orders patches numerically, never as text", () => {
    expect(patchSpan("26.9", "26.12", [])).toEqual(["26.10", "26.11", "26.12"]);
    expect(patchSpan("16.18", "26.20", [])).toEqual(["26.19", "26.20"]);
    expect(patchSpan("26.22", "26.22", [])).toEqual([]);
  });
  const h = hist([
    change({ item: "Runaan's Hurricane", itemId: "3085", patch: "26.20", type: "nerf" }),
    change({ item: "Guinsoo's Rageblade", patch: "26.18", type: "buff" }),
  ], ["26.20", "26.19", "26.18"]);
  it("counts only changes after the game's own patch, up to the live patch", () => {
    const c = checkBuild(h, { patch: "16.18", date: "2026-10-01" }, [{ id: 3085, name: "Runaan's Hurricane" }, { id: 3124, name: "Guinsoo's Rageblade" }])!;
    expect(c).toMatchObject({ played: "26.18", current: "26.20", checked: ["26.19", "26.20"], missing: [], complete: true });
    expect(c.marks.map((m) => [m.name, m.verdict])).toEqual([["Runaan's Hurricane", "nerf"]]);
    expect(c.byId[3085].changes[0].patch).toBe("26.20");
    expect(checkBuild(h, { patch: "16.20" }, [{ id: 3085, name: "Runaan's Hurricane" }])!.marks).toEqual([]);
  });
  it("says which patches are not stored instead of calling the build checked", () => {
    const c = checkBuild(hist([], ["26.20", "26.18"]), { patch: "16.17" }, [])!;
    expect(c).toMatchObject({ missing: ["26.19"], complete: false });
  });
  it("counts a mid-patch update of the game's own patch only when it is dated after the game", () => {
    const mid = hist([change({ item: "Eclipse", patch: "26.20", type: "nerf", midPatch: { title: "Mid-patch update", date: "2026-10-20" } })], ["26.20"]);
    expect(checkBuild(mid, { patch: "16.20", date: "2026-10-18" }, [{ id: 6692, name: "Eclipse" }])!.marks).toHaveLength(1);
    expect(checkBuild(mid, { patch: "16.20", date: "2026-10-21" }, [{ id: 6692, name: "Eclipse" }])!.marks).toHaveLength(0);
  });
  it("marks Opportunity removed on a build from before 26.9, and flags the record when a later game holds it", () => {
    const h22 = { ...history, external: history.external };
    const old = checkBuild(h22, { patch: "16.8" }, [{ id: 6701, name: "Opportunity" }])!;
    expect(old.marks[0]).toMatchObject({ name: "Opportunity", verdict: "removed" });
    expect(old.complete).toBe(false); // 26.9 to 26.15 are before the stored notes
    const late = checkBuild(h22, { patch: "16.20" }, [{ id: 6701, name: "Opportunity" }])!;
    expect(late.marks).toEqual([]);
    expect(late.quality[0].quality).toMatch(/recorded in a 26\.20 game, but Riot's 26\.9 notes removed it/);
  });
});

describe("recorded builds", () => {
  it("every row carries its check, by item id, and no item is marked that the build didn't buy or hold", () => {
    for (const r of rows.slice(0, 300)) {
      expect(r.itemCheck).toBeDefined();
      const held = new Set(buildItems(r.build));
      for (const m of r.itemCheck!.marks) expect(held.has(m.id)).toBe(true);
      expect(r.itemCheck!.current).toBe(history.archive.latest);
    }
  });
  it("a Common build reads each item against its own games' patches", () => {
    const h = hist([change({ item: "Runaan's Hurricane", itemId: "3085", patch: "26.20", type: "nerf" })], ["26.20", "26.19", "26.18"]);
    const mk = (patch: string) => {
      const build = { final: [3085], purchases: [[600, 3085, "buy"]] as [number, number, "buy"][], trinket: undefined };
      return { build, game: { patch }, itemCheck: checkBuild(h, { patch }, [{ id: 3085, name: "Runaan's Hurricane" }]) };
    };
    const c = commonMarks([mk("16.18"), mk("16.20")])!;
    expect(c.patches).toEqual(["26.18", "26.20"]);
    expect(c.byId[3085]).toMatchObject({ verdict: "nerf", games: { changed: 1, of: 2, patches: ["26.18"] } });
  });
});

describe("the daily workflow keeps it updated", () => {
  it("regenerates and commits the history with the patch notes", () => {
    const wf = readFileSync(join(process.cwd(), ".github/workflows/refresh-patch-notes.yml"), "utf8");
    expect(wf).toMatch(/npx tsx scripts\/item-history\.ts/);
    expect(wf).toMatch(/git add data\/patch-notes\.json data\/item-changes\.json\n/);
  });
});
